import esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import process from "process";
import builtins from "builtin-modules";

const banner = `/*\nTHIS IS A GENERATED/BUNDLED FILE BY ESBUILD\nif you want to view the source, please visit the github repository of this plugin\n*/`;

const prod = process.argv[2] === "production";
const DIST = "dist";

function ensureDist() {
  fs.mkdirSync(DIST, { recursive: true });
}

function copyManifest() {
  ensureDist();
  fs.copyFileSync("manifest.json", path.join(DIST, "manifest.json"));
}

function buildStyles() {
  ensureDist();
  const entries = fs.readdirSync("src", { recursive: true });
  const files = entries
    .filter((entry) => entry.endsWith("styles.css"))
    .map((entry) => path.join("src", entry))
    .sort();

  const css = files
    .map((file) => `/* ${file} */\n${fs.readFileSync(file, "utf8")}`)
    .join("\n\n");

  fs.writeFileSync(path.join(DIST, "styles.css"), css);
}

const buildStylesPlugin = {
  name: "build-styles",
  setup(build) {
    build.onEnd(() => {
      buildStyles();
      copyManifest();
    });
  },
};

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/*",
    "lezer",
    ...builtins,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  loader: {
    ".svg": "text",
  },
  treeShaking: true,
  outfile: path.join(DIST, "main.js"),
  plugins: [buildStylesPlugin],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  buildStyles();
  copyManifest();
  await context.watch();
}
